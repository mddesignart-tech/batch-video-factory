import { recordBenchmark } from "@/services/benchmark-evidence";

/**
 * File the one h3_max clip the first real IMPORT run bought.
 *
 * Read-only as far as any vendor is concerned: no network call, nothing spent.
 * The clip already exists and was paid for on 2026-09-18 inside batch
 * `7613ce13`, 40 credits, Runway task `dd0a31dd`.
 *
 * ## Why this sample is worth a row of its own
 *
 * It is the third clip from an ordinary production run rather than a purchase
 * made to learn something - and the first from the IMPORT path, where the
 * keyframe was supplied by the operator rather than generated by this pipeline.
 * That matters because keyframe adherence is the one thing this model has
 * consistently done well, and until now every keyframe it was given came out of
 * our own image step.
 *
 * ## How the scores were arrived at
 *
 * Nothing here is an impression. Every number that could be measured was
 * measured, with FFmpeg only:
 *
 *   subject bounding box, 21 samples at 0.25s
 *                           top y=34 and bottom y=293 of 320 at EVERY sample.
 *                           Constant scale means no zoom; a constant top edge
 *                           means no vertical drift.
 *   border-band difference  first frame vs last, on the left, right and top
 *                           bands where the subject never is. Left 0.95, right
 *                           0.88, top 1.01 YAVG, YMAX 6/255 - all three at the
 *                           noise floor, and tighter than either batch clip.
 *   scdet scene score       mean 0.0468%, max 0.197% over 124 frames, no cut.
 *                           As a fraction that is 0.00047 / 0.0020, against
 *                           0.0011 / 0.0065 for batch scene 1 and 0.0023 /
 *                           0.0151 for batch scene 4.
 *   region mean RGB         hoodie, jeans, hair, background, at six timestamps,
 *                           against the same regions of the keyframe.
 *   eye band at 4fps        21 tiles, to count blinks rather than guess.
 *
 * The figures are written down rather than described so the next model can be
 * compared against them instead of against somebody's memory.
 *
 *   npx tsx scripts/record-import-benchmark.ts [--apply]
 */

const TASK_ID = "dd0a31dd-0dd0-44c0-a730-7836858af4aa";
const MODEL_ID = "h3_max:768x1280";
const PROJECT_ID = "1ef61e94-63a3-4d1a-b09c-cb9646d00447";

const SCORES: Record<string, number> = {
  maxIdentity: 10,
  faceDrift: 8,
  handsBody: 9,
  clothingConsistency: 10,
  staysInFrame: 10,
  motion: 6,
  camera: 10,
  composition: 8,
  artifacts: 9,
  keyframeAdherence: 9,
  promptAdherence: 8,
  continuity: 7,
  shortsUsable: 9,
};

