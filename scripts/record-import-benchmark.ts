async function main(): Promise<void> {
  const apply = process.argv.includes("--apply");
  console.log("=".repeat(88));
  console.log(`  GHI BENCHMARK CLIP h3_max CUA LAN NHAP STORYBOARD THAT  ${apply ? "[GHI]" : "[DRY RUN]"}`);
  console.log("=".repeat(88));

  const job = await prisma.providerJob.findFirst({ where: { externalId: TASK_ID } });
  if (!job) {
    console.log(`\nKHONG tim thay ProviderJob ${TASK_ID}. Dung lai.`);
    process.exitCode = 1;
    return;
  }
  const scene = await prisma.scene.findUniqueOrThrow({
    where: { id: job.sceneId ?? "" },
    include: { project: true },
  });
  if (scene.projectId !== PROJECT_ID) {
    console.log(`\nClip khong thuoc du an ${PROJECT_ID}. Dung lai.`);
    process.exitCode = 1;
    return;
  }

  // Recording the same clip twice would double its weight in every average the
  // router later reads. The task id is what makes a clip one clip.
  const already = await prisma.videoBenchmark.findFirst({ where: { taskId: TASK_ID } });
  const values = Object.values(SCORES);
  const mean = values.reduce((a, b) => a + b, 0) / values.length;

  console.log(
    `\ncanh ${scene.sceneNumber}  task ${TASK_ID}\n` +
      `  du an       ${scene.project.title}\n` +
      `  clip        ${scene.videoPath}\n` +
      `  keyframe    ${scene.imagePath} (${scene.imageSource})\n` +
      `  do kho      ${scene.complexity}/${scene.spendPriority}, ${scene.duration}s\n` +
      `  chi phi     $${job.actualCost.toFixed(6)} (40 credit)\n` +
      `  diem TB     ${mean.toFixed(2)}/10 tren ${values.length} tieu chi\n` +
      `  ${Object.entries(SCORES).map(([k, v]) => `${k}=${v}`).join(" ")}`,
  );

  if (already) {
    console.log("\n  DA CO ban ghi cho task nay, khong ghi de.");
  } else if (!apply) {
    console.log("\n  (dry run - chua ghi)");
  } else {
    await recordBenchmark({
      provider: "runway",
      model: MODEL_ID,
      taskId: TASK_ID,
      projectId: scene.projectId,
      sceneNumber: scene.sceneNumber,
      complexity: scene.complexity as "LOW" | "MEDIUM" | "HIGH",
      // The band is what the classifier stored; it never stored the number.
      // Passing 0 is honest, inventing one to fill the column is not.
      complexityScore: 0,
      characterCount: 1,
      promptSent: scene.videoPrompt,
      durationRequested: scene.duration,
      durationSent: 5,
      keyframePath: scene.imagePath ?? "",
      outcome: "succeeded",
      credits: 40,
      actualCost: job.actualCost,
      // Wall clock from create to download, so it includes polling. Kept as
      // measured rather than trimmed to a guess at vendor compute time.
      generationMs: 144_661,
      outputPath: scene.videoPath ?? "",
      scores: SCORES,
      notes: NOTES,
    });
    console.log("\n  da ghi VideoBenchmark.");
  }

  const rows = await prisma.videoBenchmark.findMany({
    where: { model: MODEL_ID, outcome: "succeeded" },
    orderBy: { createdAt: "asc" },
  });
  console.log(`\nTat ca mau ${MODEL_ID} da cham (${rows.length}):`);
  for (const r of rows) {
    const s = Object.values(JSON.parse(r.scoresJson || "{}")) as number[];
    const avg = s.length ? (s.reduce((a, b) => a + b, 0) / s.length).toFixed(2) : "-";
    console.log(
      `  ${r.createdAt.toISOString().slice(0, 10)}  canh ${String(r.sceneNumber).padEnd(2)} ` +
        `${r.complexity.padEnd(6)} ${r.characterCount} nv  ${String(avg).padStart(5)}/10  ` +
        `$${r.actualCost.toFixed(2)}  ${r.projectId?.slice(0, 8)}`,
    );
  }
  console.log(
    "\nKHONG doi lifecycle, reliability hay verification cua model. Ba mau san xuat\n" +
      "that khong mo rong duoc pham vi bang chung: ca ba deu LOW, 1 nhan vat, camera\n" +
      "khoa, co keyframe - dung bang hinh dang ma cong LOW_AUTO dang cho qua.\n",
  );
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
